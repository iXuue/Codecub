def _verdict(ci, point, field_note=""):
    """Map a paired delta + CI to a directional verdict string."""
    if ci is None or ci[0] is None:
        return "inconclusive (insufficient data)"
    if ci[0] > 0:
        return f"positive direction, CI [{ci[0]}, {ci[1]}] excludes 0"
    if ci[1] < 0:
        return f"negative direction, CI [{ci[0]}, {ci[1]}] excludes 0"
    return f"inconclusive (CI [{ci[0]}, {ci[1]}] crosses 0)"


